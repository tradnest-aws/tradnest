export const localeFromPathname = (pathname: string | null | undefined) => {
  const match = pathname?.match(/^\/([a-z]{2})(?:\/|$)/i)
  return (match?.[1] || DEFAULT_STOREFRONT_LOCALE).toLowerCase()
}

